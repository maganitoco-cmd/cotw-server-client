# ── Timing database ─────────────────────────────────────────────────
TIMINGS = []  # list of dicts: phase, action, endpoint, http, elapsed_ms, result

def record_timing(phase, action, endpoint, http_code, elapsed_ms, result):
    TIMINGS.append({
        "phase": phase,
        "action": action,
        "endpoint": endpoint[:80],
        "http": http_code,
        "elapsed_ms": elapsed_ms,
        "result": str(result)[:20]
    })

def generate_timing_report():
    """Write e2e_timing_report.md from TIMINGS."""
    if not TIMINGS:
        return
    report_path = os.path.join(os.path.dirname(__file__), "e2e_timing_report.md")
    total_ms = sum(t["elapsed_ms"] for t in TIMINGS)
    total_calls = len(TIMINGS)
    
    lines = []
    lines.append("# E2E Timing Report — Quest Economy\n")
    lines.append(f"**Date**: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
    lines.append(f"**Total calls**: {total_calls}  \n")
    lines.append(f"**Total time**: {total_ms}ms ({total_ms/1000:.1f}s)  \n")
    lines.append(f"**Average**: {total_ms/total_calls:.0f}ms/call  \n")
    lines.append("")
    
    # Slowest calls summary
    sorted_timings = sorted(TIMINGS, key=lambda t: t["elapsed_ms"], reverse=True)
    lines.append("## Slowest Calls (Top 10)\n")
    lines.append("| # | Phase | Endpoint | ms |")
    lines.append("|---|---|---|---|")
    for i, t in enumerate(sorted_timings[:10]):
        lines.append(f"| {i+1} | {t['phase']} | {t['endpoint']} | {t['elapsed_ms']} |")
    lines.append("")
    
    # Summary by phase
    lines.append("## Summary by Phase\n")
    phases = {}
    for t in TIMINGS:
        p = t["phase"]
        if p not in phases:
            phases[p] = {"calls": 0, "total_ms": 0}
        phases[p]["calls"] += 1
        phases[p]["total_ms"] += t["elapsed_ms"]
    lines.append("| Phase | Calls | Total ms | Avg ms |")
    lines.append("|---|---|---|---|")
    for p, d in phases.items():
        lines.append(f"| {p} | {d['calls']} | {d['total_ms']} | {d['total_ms']//d['calls']} |")
    lines.append("")
    
    # Full per-call table
    lines.append("## Per-Call Timing\n")
    lines.append("| # | Phase | Action | Endpoint | HTTP | ms | Result |")
    lines.append("|---|---|---|---|---|---|---|")
    for i, t in enumerate(TIMINGS):
        lines.append(f"| {i+1} | {t['phase']} | {t['action']} | {t['endpoint']} | {t['http']} | {t['elapsed_ms']} | {t['result']} |")
    lines.append("")
    lines.append("---")
    lines.append(f"_Generated by E2E test on {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}_")
    
    with open(report_path, "w") as f:
        f.write("\n".join(lines))
    print(f"\n  📊 Reporte guardado: {report_path}")


