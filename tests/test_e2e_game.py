def api(endpoint, silent=False, phase="", action=""):
    """Call COTW API. Returns parsed JSON dict or None on network error."""
    global ID_USER, USER_COORDS
    url = f"{BASE}/{endpoint}"
    if "deviceId=" not in url:
        sep = "&" if "?" in url else "?"
        url += f"{sep}deviceId={DEVICE_ID}"
    if ID_USER and "idUser=" not in url:
        url += f"&idUser={ID_USER}"

    for attempt in range(2):
        try:
            start = time.time()
            with urllib.request.urlopen(url, timeout=60) as resp:
                data = json.loads(resp.read().decode())
            elapsed = int((time.time() - start) * 1000)
            http_code = resp.status
        except Exception as e:
            if not silent:
                print(f"  🌐 NETWORK ERROR (attempt {attempt+1}): {e}")
            time.sleep(1)
            continue

        result = data.get("result")
        record_timing(phase, action, endpoint, http_code, elapsed, result)

        if result == -1:
            msg = (data.get("Message") or data.get("message") or "Unknown error")[:300]
            print(f"  ❌ result=-1: {msg}")
        elif result == 0:
            msg = (data.get("Message") or data.get("message") or "")[:150]
            if not silent:
                print(f"  ⚠️  result=0: {msg}")
        elif not silent:
            size = len(json.dumps(data, default=str))
            print(f"  ✅ HTTP 200 | result={result} | {elapsed}ms | {size}B")

        # Auto-extract ID_USER from User._id
        u = data.get("User")
        if u and u.get("_id"):
            uid = u["_id"]
            ID_USER = uid.get("$oid", uid) if isinstance(uid, dict) else uid

        # Auto-extract coordinates
        p = data.get("User", {}).get("Player", {})
        coords = p.get("Coordinates")
        if coords:
            USER_COORDS = coords

        return data

    return None


def node_of(data, id_building):
    if not data:
        return None
    for b in (data.get("User", {}) or {}).get("Buildings", []):
        if b.get("idBuilding") == id_building:
            return b.get("Node")
    return None


def level_of(data, id_building):
    if not data:
        return 0
    for b in (data.get("User", {}) or {}).get("Buildings", []):
        if b.get("idBuilding") == id_building:
            return b.get("Level", 0)
    return 0


def has_building(data, id_building):
    if not data:
        return False
    return any(
        b.get("idBuilding") == id_building
        for b in (data.get("User", {}) or {}).get("Buildings", [])
    )


def collect_all(data, phase=""):
    """Attempt to collect from all existing building nodes."""
    if not data:
        return
    blds = (data.get("User", {}) or {}).get("Buildings", [])
    for b in blds:
        node = b.get("Node")
        if node:
            r = api(f"BUILDINGS?action=collect&Node={node}", silent=True, phase=phase, action="collect")
            if r and r.get("result") == 1:
                resources = r.get("Resources", {})
                gold = resources.get("Gold", {}) if isinstance(resources, dict) else {}
                gold_qty = gold.get("Quantity", "?")
                print(f"    Recolectado Node={node} | gold={gold_qty}")


def get_resources(data):
    """Return dict of current resource quantities."""
    u = data.get("User", {}) if data else {}
    return {
        "Gold": (u.get("Gold", {}) or {}).get("Quantity", 0) or 0,
        "Food": (u.get("Food", {}) or {}).get("Quantity", 0) or 0,
        "Wood": (u.get("Wood", {}) or {}).get("Quantity", 0) or 0,
        "Stone": (u.get("Stone", {}) or {}).get("Quantity", 0) or 0,
        "Ore": (u.get("Ore", {}) or {}).get("Quantity", 0) or 0,
    }


def get_items(data):
    """Return list of items from User.Items."""
    u = data.get("User", {}) if data else {}
    return u.get("Items", []) or []


def check_quests(phase=""):
    """Check quests and collect any completed rewards. Returns data if collected.
    Note: Server-side questDao has NPE bug for fresh accounts — gracefully handled.
    """
    r = api("QUEST?action=rewards&idQuest=0", silent=True, phase=phase, action="quest_rewards")
    if r and r.get("result") == 1:
        quests = r.get("Quests", []) or []
        completed = [q for q in quests if q.get("Completed")]
        if completed:
            print(f"    🎯 Misiones completadas: {len(completed)}")
            for q in completed:
                qid = q.get("idQuest", q.get("_id", "?"))
                cr = api(f"QUEST?action=collectQ&idQuest={qid}", silent=True, phase=phase, action=f"collectQ_{qid}")
                if cr and cr.get("result") == 1:
                    items = cr.get("User", {}).get("Items", []) or []
                    if items:
                        print(f"      Cobrada misión {qid}: {len(items)} items obtenidos")
                    else:
                        print(f"      Cobrada misión {qid}")
            return True
        else:
            print(f"    🎯 Sin misiones completadas (de {len(quests)} pendientes)")
            return True  # quest system works, just nothing to collect
    return False


def check_daily_quests(phase=""):
    """Check and collect daily quests. Graciously handles server-side bugs."""
    r = api("QUEST?action=rewardsD&idQuest=0", silent=True, phase=phase, action="quest_rewardsD")
    if r and r.get("result") == 1:
        dq = r.get("DailyQuests", []) or []
        completed = [q for q in dq if q.get("Completed")]
        if completed:
            print(f"    📅 Diarias completadas: {len(completed)}")
            cr = api("QUEST?action=collectD", silent=True, phase=phase, action="collectD")
            if cr and cr.get("result") == 1:
                print(f"      📅 Diarias cobradas")
                return True
    return False


def collect_daily_reward(phase=""):
    """Collect daily reward. Graciously handles server-side NPE bug."""
    r = api("USER?action=dailyReward", silent=True, phase=phase, action="dailyReward")
    if r and r.get("result") == 1:
        print(f"    🎁 Recompensa diaria cobrada")
        return True
    return False


def open_resource_chests(phase=""):
    """Try to open each resource chest item."""
    data = api("USER?action=loginJustUser", silent=True, phase=phase, action="login_items_check")
    if not data:
        return
    items = get_items(data)
    chests = [i for i in items if i.get("Type", "").lower() in ("chest", "chests")]
    if not chests:
        return
    print(f"    🎁 Abriendo {len(chests)} cofres...")
    for chest in chests:
        r = api(f"ITEMS?action=materialChest&idItem={chest['idItem']}&Quantity={chest.get('Quantity',1)}",
                silent=True, phase=phase, action="open_chest")
        if r and r.get("result") == 1:
            print(f"      Cofre #{chest['idItem']} abierto")


def use_resource_items(phase="", force=False):
    """Use resource items from inventory if resources are low."""
    data = api("USER?action=loginJustUser", silent=True, phase=phase, action="login_resource_check")
    if not data:
        return 0
    res = get_resources(data)
    items = get_items(data)
    
    # Find resource items (non-speedup, non-chest)
    res_items = [i for i in items if i.get("Type", "").lower() == "resources" or i.get("Type", "").lower() == "resource"]
    
    used = 0
    for item in res_items:
        qty = item.get("Quantity", 0) or 0
        if qty > 0:
            # Check if gold is low (primary resource we care about)
            if res.get("Gold", 0) < 50000 or force:
                r = api(f"ITEMS?action=use&idItem={item['idItem']}&Quantity={min(qty, 5)}",
                        silent=True, phase=phase, action="use_item")
                if r and r.get("result") == 1:
                    print(f"      📦 Item #{item['idItem']} usado")
                    used += 1
                    # Re-check resources
                    res = get_resources(r)
                    if res.get("Gold", 0) >= 100000:
                        break
    
    # Also check for speedup items — note them
    speedup_items = [i for i in items if "speed" in i.get("Type", "").lower()]
    if speedup_items and not force:
        for s in speedup_items[:3]:
            print(f"      ⏱️ SpeedUp #{s['idItem']} x{s.get('Quantity',1)} disponible")
    
    return used


def try_complete_construct(cid, label="", phase=""):
    """Try to check construct status and complete it.
    Returns True if construct seems done.
    Attempts: remainingTime → speedUpGold → speedUpItems → sleep+retry
    """
    if not cid:
        return False
    time.sleep(1)
    r = api(f"CONSTRUCT?action=remainingTime&idConstruct={cid}", silent=True, phase=phase, action=f"remainingTime_{label}")
    if r and r.get("result") == 1:
        remaining = r.get("RemainingTime", 999)
        status = r.get("Status", r.get("status", ""))
        print(f"    {label}: remainingTime={remaining}s status={status}")
        if isinstance(remaining, (int, float)):
            if remaining <= 1:
                return True
            # Try speedUpGold first
            speed_r = api(f"CONSTRUCT?action=speedUpGold&idConstruct={cid}", silent=True, phase=phase, action=f"speedUpGold_{label}")
            if speed_r and speed_r.get("result") == 1:
                print(f"    {label}: speedUpGold OK")
                return True
            else:
                msg = speed_r.get("Message", "")[:100] if speed_r else ""
                if msg:
                    print(f"    {label}: speedUpGold -> {msg}")
                # Try speedup items
                if "RESOURCES" in msg or "resources" in msg or not msg:
                    data = api("ITEMS?action=timeItems", silent=True, phase=phase, action="timeItems")
                    if data and data.get("result") == 1:
                        items = data.get("Items", []) or []
                        if items:
                            for si in items[:3]:
                                sid = si.get("idItem", "1001")
                                sqty = min(si.get("Quantity", 1) or 1, 5)
                                sp_r = api(f"CONSTRUCT?action=speedUpItems&idConstruct={cid}&Items={sid}.{sqty}",
                                           silent=True, phase=phase, action=f"speedUpItems_{label}")
                                if sp_r and sp_r.get("result") == 1:
                                    print(f"    {label}: speedUpItems OK (Item #{sid} x{sqty})")
                                    return True
                    # Last resort: wait a bit and retry
                    time.sleep(3)
                    r2 = api(f"CONSTRUCT?action=remainingTime&idConstruct={cid}", silent=True, phase=phase, action=f"remainingTime2_{label}")
                    if r2 and r2.get("result") == 1:
                        rem2 = r2.get("RemainingTime", 999)
                        print(f"    {label}: retry remainingTime={rem2}s")
                        if rem2 <= 1 or rem2 < remaining:
                            return rem2 <= 1
    elif r and r.get("result") == -1:
        msg = r.get("Message", "")[:200]
        if "not" in msg.lower() or "exist" in msg.lower() or "invalid" in msg.lower():
            print(f"    {label}: constructo ya completado ({msg[:80]})")
            return True
        print(f"    {label}: remainingTime error: {msg}")
    return False


def refresh(phase=""):
    """Re-login and return data."""
    data = api("USER?action=loginJustUser", silent=True, phase=phase, action="refresh")
    return data


def section(n, title):
    print(f"\n{'=' * 60}")
